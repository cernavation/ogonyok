/**
-- ============================================================================
-- lib/server/prompts/milestone.ts: ПРОМПТЫ ЮБИЛЕЙНЫХ ВЕХ (100, 200, 300... ДНЕЙ)
-- ============================================================================
-- Pro: связующий аналитический текст на основе точных цифр, посчитанных кодом.
-- Ultra: глубокий анализ трансформации, «Письмо к себе через 100 дней» по 5 строгим правилам:
--   1) Никаких выдумок (галлюцинаций) — только факты из записей.
--   2) При трагедии/потере — мужское уважительное признание, а не «давай ещё».
--   3) Никаких психологических диагнозов.
--   4) Без дежурных восторгов — тон спокойный, зрелый, поддерживающий.
--   5) Длина: 150-250 слов, ровно 3 абзаца (Исток, Горнило, Вектор).
-- ============================================================================
*/

export interface MilestoneStatsSummary {
  milestoneNumber: number
  totalPrides: number
  totalGratitudes: number
  averageScore: number
  highestDayScore: number
  topTags: Array<{ tag: string; count: number }>
  overcomeDistribution: {
    level0: number
    level1: number
    level2: number
    level3: number
  }
  decadeDynamics: Array<{
    decadeIndex: number
    title: string
    averageScore: number
    pridesCount: number
  }>
}

/**
 * Промпт для тарифа PRO:
 * ИИ не выдумывает цифры, а пишет строгие текстовые связки и выводы
 * на основе готовых математических агрегатов.
 */
export function buildProMilestonePrompt(stats: MilestoneStatsSummary): string {
  const topTagsStr = stats.topTags.map((t) => `${t.tag} (${t.count})`).join(', ') || 'нет данных'
  const decadesStr = stats.decadeDynamics
    .map((d) => `${d.title}: ${d.pridesCount} побед, ср. балл ${d.averageScore.toFixed(1)}★`)
    .join('\n')

  return `ЗАДАЧА:
Сформируй краткий аналитический обзор вехи #${stats.milestoneNumber} дней для тарифа Премиум.
Все цифры уже вычислены кодом. Твоя роль — дать лаконичный, фактологический комментарий к динамике.

ФАКТЫ И МЕТРИКИ ЗА ${stats.milestoneNumber} ДНЕЙ:
- Всего записано гордостей: ${stats.totalPrides}
- Всего зафиксировано благодарностей: ${stats.totalGratitudes}
- Средний балл дня: ${stats.averageScore.toFixed(1)}★
- Максимальный балл дня: ${stats.highestDayScore.toFixed(1)}★
- Распределение преодоления: уровень 0: ${stats.overcomeDistribution.level0}, уровень 1: ${stats.overcomeDistribution.level1}, уровень 2: ${stats.overcomeDistribution.level2}, уровень 3: ${stats.overcomeDistribution.level3}
- Ключевые теги фокуса: ${topTagsStr}
- Динамика по декадам:
${decadesStr}

ПРАВИЛА:
1. Опирайся только на приведённые цифры.
2. Не давай «письма себе» или художественных метафор (это прерогатива Ultra).
3. Тон деловой, сдержанный, подтверждающий дисциплину.
4. Верни чистый JSON следующего формата:

{
  "title": "Анализ рубежа ${stats.milestoneNumber} дней",
  "summary": "1-2 предложения с итоговой оценкой плотности результатов",
  "dynamicsComment": "2-3 предложения о том, как менялась интенсивность по декадам",
  "tagsComment": "1-2 предложения о ключевых опорах и тегах автора"
}`
}

/**
 * Промпт для тарифа ULTRA:
 * Глубокая персонализация, смысловой анализ трансформации характера
 * и «Письмо к себе через 100 дней» по 5 строгим правилам.
 */
export function buildUltraMilestonePrompt(params: {
  milestoneNumber: number
  stats: MilestoneStatsSummary
  dayHighlights: Array<{
    dayNumber: number
    prides: string[]
    gratitudes: string[]
    score?: number
  }>
}): string {
  const { milestoneNumber, stats, dayHighlights } = params

  const sampleHighlights = dayHighlights
    .slice(0, 30)
    .map((d) => `[День #${d.dayNumber}] Гордости: ${d.prides.slice(0, 2).join('; ')} | Благодарность: ${d.gratitudes.slice(0, 1).join('; ')}`)
    .join('\n')

  return `ТЫ — МЕНТОР ЛИЧНОЙ СИЛЫ СИСТЕМЫ «ОГОНЁК».
Автор летописи достиг рубежа #${milestoneNumber} дней непрерывного огня побед.
Перед тобой данные его пути: цифры и выборка записей за этот период.

МЕТРИКИ ЗА ${milestoneNumber} ДНЕЙ:
- Зафиксировано побед: ${stats.totalPrides}
- Средний балл: ${stats.averageScore.toFixed(1)}★
- Преодолений высокого уровня (2-3): ${stats.overcomeDistribution.level2 + stats.overcomeDistribution.level3}
- Главные опоры: ${stats.topTags.map((t) => t.tag).join(', ')}

ВЫБОРКА РЕАЛЬНЫХ ЗАПИСЕЙ ИЗ ЛЕТОПИСИ:
${sampleHighlights}

5 ЖЕЛЕЗНЫХ ПРАВИЛ ДЛЯ ПИСЬМА К СЕБЕ (НАРУШЕНИЕ НЕДОПУСТИМО):
1. НИКАКИХ ВЫДУМОК (ГАЛЛЮЦИНАЦИЙ): ссылайся строго на факты, действия, привычки и контекст из предоставленных записей. Запрещено сочинять несуществующие события.
2. ЕСЛИ В ЗАПИСЯХ ВСТРЕЧАЕТСЯ ПОТЕРЯ, ТРАГЕДИЯ ИЛИ СРЫВ: отвечай уважительным признанием человеческой боли и стойкости, а не лозунгами «ты молодец, давай ещё».
3. НИКАКИХ МЕДИЦИНСКИХ ИЛИ ПСИХОЛОГИЧЕСКИХ ДИАГНОЗОВ: не используй терминологию клинической психотерапии.
4. БЕЗ ДЕЖУРНЫХ ВОСТОРГОВ: тон спокойный, зрелый, мужской/братский, поддерживающий, основанный на твёрдом взгляде на реальность.
5. ОБЪЁМ И СТРУКТУРА: строго от 150 до 250 слов, ровно 3 абзаца:
   - Абзац 1 (Исток): Точка старта. С каким трением, сомнениями или рутиной начинались первые дни.
   - Абзац 2 (Горнило): Испытания и перелом. Где характер сопротивлялся, через какие препятствия пришлось продираться, что изменилось в привычках.
   - Абзац 3 (Вектор): Истинная трансформация и направление следующей сотни дней. Куда теперь направлен прицел.

ВЕРНИ ТОЛЬКО СТРОГИЙ JSON БЕЗ РАЗМЕТКИ С ТАКОЙ СТРУКТУРОЙ:
{
  "letterToSelf": "Текст письма к себе строго из 3 абзацев (Исток, Горнило, Вектор) объёмом 150-250 слов",
  "transformationSummary": "2-3 предложения о том, как изменился фокус автора: какие темы ушли, какие стали опорой",
  "coreTheme": "Главный лейтмотив пройденных ${milestoneNumber} дней (например: 'Отказ от оправданий' или 'Укоренение в дисциплине')",
  "nextMilestoneFocus": "Конкретный вызов и вектор для следующих 100 дней"
}`
}
