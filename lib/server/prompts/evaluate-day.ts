/**
-- ============================================================================
-- lib/server/prompts/evaluate-day.ts: ПРОМПТ ОЦЕНКИ ДНЯ
-- ============================================================================
-- Правила оценки гордостей (1.0 - 10.0★), преодоления (0-3), тегов.
-- Разделение логики тарифов Pro vs Ultra:
-- - Pro: баллы по шкале, преодоление, теги, краткий разбор БЕЗ напутствия ментора.
-- - Ultra: полная церемония — баллы, разбор, вердикт Ментора, теги.
-- ============================================================================
*/

import type { SubscriptionTier } from '@/lib/ogonek/permissions'

export function buildDayEvaluationPrompt(params: {
  prides: string[]
  gratitudes: string[]
  tier: SubscriptionTier
}): string {
  const { prides, gratitudes, tier } = params
  const isUltra = tier === 'ultra'

  const formattedPrides = prides.length > 0
    ? prides.map((p, i) => `${i + 1}. ${p}`).join('\n')
    : '1. Нет записей гордости'

  const formattedGratitudes = gratitudes.length > 0
    ? gratitudes.map((g, i) => `${i + 1}. ${g}`).join('\n')
    : '1. Нет записей благодарности'

  return `ЗАДАЧА:
Оцени записи сегодняшнего дня автора летописи «Огонёк».

КРИТЕРИИ ОЦЕНКИ КАЖДОЙ ГОРДОСТИ (ОТ 1.0 ДО 10.0★):
- 1.0 - 2.0★: Бессмысленный текст, спам, опечатки, заглушки. Оценка строго 1.0-2.0!
- 3.0 - 4.9★: Минимальное или тривиальное действие без преодоления сопротивления.
- 5.0 - 7.0★: Обычные бытовые дела, базовая гигиена, рутина.
- 7.1 - 8.9★: Преодоление лени, спорт, интенсивная тренировка, волевое сверхусилие.
- 9.0 - 10.0★: Исключительный триумф, марафон, закрытие ключевой сделки, прорыв сквозь сильный страх.

ШКАЛА ПРЕОДОЛЕНИЯ (overcome):
- 0: Рутина без сопротивления
- 1: Лёгкое преодоление комфорта
- 2: Серьёзное волевое преодоление
- 3: Прорыв через страх или боль

СТРОГИЕ ПРАВИЛА:
1. Запрещены одинаковые шаблонные баллы (например всем ставить 8.8)! Оценивай каждый пункт индивидуально.
2. БЛАГОДАРНОСТИ НЕ ОЦЕНИВАЮТСЯ ЦИФРАМИ И ЗВЁЗДАМИ! Тексты благодарностей используй исключительно как контекст состояния автора.
${isUltra
  ? '3. Для поля "verdict" дай глубокое, сильное напутствие Ментора в 1-3 предложениях, связывающее преодоление и благодарность.'
  : '3. ТАРИФ PRO: напутствие Ментора НЕ ВКЛЮЧЕНО. Оставь поле "verdict" пустым строковым значением ("").'}

ГОРДОСТИ ДНЯ:
${formattedPrides}

БЛАГОДАРНОСТИ ДНЯ:
${formattedGratitudes}

ВЕРНИ ТОЛЬКО СТРОГИЙ JSON БЕЗ MARKDOWN-РАЗМЕТКИ В ТАКОМ ФОРМАТЕ:
{
  "prideEvaluations": [
    {
      "num": 1,
      "score": 8.4,
      "comment": "Лаконичный честный разбор конкретно этого действия",
      "overcome": 2,
      "tags": ["#Спорт", "#Дисциплина"]
    }
  ],
  "breakdown": "Краткий честный разбор дня в 1-2 предложениях",
  "verdict": "${isUltra ? 'Мудрое напутствие Ментора личной силы' : ''}"
}`
}
